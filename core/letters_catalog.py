def _d(slug: str, name: str, category: str, desc: str, kind: str,
       groups: list[str], opening: str = "", closing: str = "",
       salutation: str = "Dear Sir/Madam", *, legal: bool = False,
       sign_roles: list[str] | None = None, keywords: str = "") -> dict[str, Any]:
    return {
        "slug": slug,
        "name": name,
        "category": category,
        "desc": desc,
        "kind": kind,
        "groups": groups,
        "opening": opening,
        "closing": closing,
        "salutation": salutation,
        "legal": legal,
        "sign_roles": sign_roles or [],
        "keywords": keywords.lower(),
    }


