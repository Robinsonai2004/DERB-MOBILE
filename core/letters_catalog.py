"""
Letters & Documents catalog for DERB MOBILE.

This module is the single source of truth for "what letters and documents
exist". The landing page, the dynamic forms, the document composer and the
exporters all read from here - so adding a new document type later means
adding ONE entry to DOC_TYPES below. Nothing else changes.

    CATALOG  ->  FORM FIELDS  ->  COMPOSED DOCUMENT  ->  PREVIEW / PDF / DOCX

Document kinds
--------------
letter       prose document (Dear ... / Yours faithfully)
agreement    structured parties/clauses/execution document
declaration  first-person sworn-style statement

Re-usable field groups keep the catalog small: a group is instantiated with a
role label and a prefix, e.g. "person:Seller:seller" produces seller_full_name,
seller_address, ... and prints under the heading "Seller".
"""

