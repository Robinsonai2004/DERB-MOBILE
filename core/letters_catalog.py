DOC_TYPES_BY_SLUG = {d["slug"]: d for d in DOC_TYPES}
DOCS_BY_CATEGORY: dict[str, list[dict[str, Any]]] = {}
for _doc in DOC_TYPES:
    DOCS_BY_CATEGORY.setdefault(_doc["category"], []).append(_doc)


def get_doc(slug: str) -> dict[str, Any] | None:
    return DOC_TYPES_BY_SLUG.get(slug)


def search_docs(query: str) -> list[dict[str, Any]]:
    """Match a query against name, description, keywords and category."""
    q = (query or "").strip().lower()
    if not q:
        return []
    out = []
    for doc in DOC_TYPES:
        cat = CATEGORIES_BY_SLUG[doc["category"]]["name"]
        haystack = f"{doc['name']} {doc['desc']} {doc['keywords']} {cat}".lower()
        if all(term in haystack for term in q.split()):
            out.append(doc)
    return out


def field_instances(doc: dict[str, Any]) -> list[dict[str, Any]]:
    """
    Expand a doc's group tokens into concrete field lists.

    Each instance: {key, group, role, prefix, fields: [{name,label,type,...}]}
    Field name is 'prefix_fieldname' (or bare 'fieldname' when no prefix);
    label is 'Role FieldLabel' when a role is given.
    """
    instances: list[dict[str, Any]] = []
    for token in doc["groups"]:
        parts = token.split(":")
        group_key = parts[0]
        role = parts[1] if len(parts) > 1 and parts[1] else ""
        prefix = parts[2] if len(parts) > 2 and parts[2] else ""
        if not prefix and role:
            prefix = role.split(" ")[0].split("/")[0].lower()
        fields = []
        for field_name in GROUP_FIELDS[group_key]:
            fdef = FIELD_DEFS[field_name]
            label = f"{role} {fdef['label']}" if role else fdef["label"]
            fields.append({
                "name": f"{prefix}_{field_name}" if prefix else field_name,
                "label": label,
                "type": fdef["type"],
                "placeholder": fdef.get("placeholder", ""),
                "inputmode": fdef.get("inputmode", ""),
            })
        heading = role or group_key.replace("_", " ").title()
        if heading == "Document Date":
            heading = "Date"
        instances.append({
            "key": prefix or group_key,
            "group": group_key,
            "role": role,
            "heading": heading,
            "fields": fields,
        })
    return instances


ALL_FIELDS_CACHE: dict[str, list[dict[str, Any]]] = {}


def fields_for(slug: str) -> list[dict[str, Any]]:
    doc = get_doc(slug)
    if doc is None:
        return []
    if slug not in ALL_FIELDS_CACHE:
        ALL_FIELDS_CACHE[slug] = field_instances(doc)
    return ALL_FIELDS_CACHE[slug]


def flat_fields(doc: dict[str, Any]) -> list[dict[str, Any]]:
    """All concrete fields of a doc, flattened (for form parsing)."""
    return [f for inst in field_instances(doc) for f in inst["fields"]]
